import esbuild from 'esbuild';
import process from 'node:process';
import { builtinModules } from 'node:module';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
do not edit directly — see main.ts + src/
*/
`;

const mode = process.argv[2] ?? 'dev';

if (!['dev', 'production', 'harness'].includes(mode)) {
  throw new Error(`Invalid mode: ${mode}`);
}

// The harness bundles the renderer for a plain browser page (no Obsidian), for UI checks.
const options =
  mode === 'harness'
    ? {
        entryPoints: ['dev/harness.ts'],
        bundle: true,
        format: 'iife',
        target: 'es2020',
        logLevel: 'info',
        sourcemap: 'inline',
        outfile: 'dev/harness.js',
      }
    : {
        banner: { js: banner },
        entryPoints: ['main.ts'],
        bundle: true,
        external: [
          'obsidian',
          'electron',
          '@codemirror/autocomplete',
          '@codemirror/collab',
          '@codemirror/commands',
          '@codemirror/language',
          '@codemirror/lint',
          '@codemirror/search',
          '@codemirror/state',
          '@codemirror/view',
          '@lezer/common',
          '@lezer/highlight',
          '@lezer/lr',
          ...builtinModules,
          ...builtinModules.map((m) => `node:${m}`),
        ],
        format: 'cjs',
        target: 'es2020',
        logLevel: 'info',
        sourcemap: mode === 'production' ? false : 'inline',
        treeShaking: true,
        outfile: 'main.js',
        minify: mode === 'production',
      };

const ctx = await esbuild.context(options);

if (mode === 'dev') {
  await ctx.watch();
} else {
  await ctx.rebuild();
  await ctx.dispose();
}
