import esbuild from 'esbuild';
import process from 'node:process';
import { builtinModules } from 'node:module';
import { readFile } from 'node:fs/promises';

const licenses = await Promise.all(['LICENSE', 'THIRD_PARTY_NOTICES.txt'].map((path) => readFile(path, 'utf8')));
const banner = `/*!
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
do not edit directly — see main.ts + src/
${licenses.join('\n\n').replaceAll('*/', '* /')}
*/
`;

const mode = process.argv[2] ?? 'dev';

if (!['dev', 'production', 'harness'].includes(mode)) {
  throw new Error(`Invalid mode: ${mode}`);
}

// The harness bundles the renderer for a plain browser page (no Obsidian), for UI checks.
const options =
  mode === 'harness'
    ? {
        entryPoints: ['dev/harness.ts'],
        bundle: true,
        format: 'iife',
        target: 'es2020',
        logLevel: 'info',
        sourcemap: 'inline',
        outfile: 'dev/harness.js',
      }
    : {
        banner: { js: banner },
        entryPoints: ['main.ts'],
        bundle: true,
        external: [
          'obsidian',
          'electron',
          '@codemirror/autocomplete',
          '@codemirror/collab',
          '@codemirror/commands',
          '@codemirror/language',
          '@codemirror/lint',
          '@codemirror/search',
          '@codemirror/state',
          '@codemirror/view',
          '@lezer/common',
          '@lezer/highlight',
          '@lezer/lr',
          ...builtinModules,
          ...builtinModules.map((m) => `node:${m}`),
        ],
        format: 'cjs',
        target: 'es2020',
        logLevel: 'info',
        sourcemap: mode === 'production' ? false : 'inline',
        treeShaking: true,
        outfile: 'main.js',
        minify: mode === 'production',
        metafile: true,
      };

const ctx = await esbuild.context(options);

if (mode === 'dev') {
  await ctx.watch();
} else {
  try {
    const result = await ctx.rebuild();
    if (mode === 'production') {
      const manifest = JSON.parse(await readFile('manifest.json', 'utf8'));
      const nodeModules = new Set([...builtinModules, ...builtinModules.map((name) => `node:${name}`), 'electron']);
      const imports = Object.values(result.metafile.outputs).flatMap((output) => output.imports);
      if (!manifest.isDesktopOnly && imports.some((entry) => entry.external && nodeModules.has(entry.path))) {
        throw new Error('Mobile-compatible plugins must not require Node.js or Electron at runtime.');
      }
    }
  } finally {
    await ctx.dispose();
  }
}
